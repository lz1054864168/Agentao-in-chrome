def _extract_html_from_docx(data: bytes) -> str:











    """Extract content from a .docx file as HTML, preserving tables and images.























    Uses python-docx to walk the document body in order (paragraphs and











    tables interleaved), emitting semantic HTML. Embedded images are











    base64-encoded as data URIs so they survive the text-only prompt











    channel — the LLM sees ``<img>`` tags with inline data.











    """











    import base64











    import io























    try:











        import docx











        from docx.oxml.ns import qn











    except ImportError:











        return "[python-docx not installed; cannot parse .docx]"























    try:











        doc = docx.Document(io.BytesIO(data))























        # Build a lookup from relationship ID -> image data URI so we can











        # resolve <a:blip r:embed="rId..."/> references inside runs.











        image_map = {}











        for rel in doc.part.rels.values():











            if "image" in rel.reltype:











                try:











                    blob = rel.target_part.blob











                    ct = rel.target_part.content_type











                    b64 = base64.b64encode(blob).decode("ascii")











                    image_map[rel.rId] = f"data:{ct};base64,{b64}"











                except Exception:











                    pass























        def para_to_html(para):











            # Map Word style names to HTML tags.











            style_name = (para.style.name or "").lower() if para.style else ""











            if style_name.startswith("heading 1") or style_name == "title":











                tag = "h1"











            elif style_name.startswith("heading 2"):











                tag = "h2"











            elif style_name.startswith("heading 3"):











                tag = "h3"











            elif style_name.startswith("heading"):











                tag = "h4"











            elif style_name.startswith("list"):











                tag = "li"











            else:











                tag = "p"























            # Collect runs, resolving embedded images.











            parts = []











            for run in para.runs:











                # Check for inline images inside this run's XML.











                blips = run._element.findall(











                    ".//" + qn("a:blip")











                )











                for blip in blips:











                    embed = blip.get(qn("r:embed"))











                    if embed and embed in image_map:











                        parts.append(











                            f'<img src="{image_map[embed]}" alt="embedded image" />'











                        )











                if run.text:











                    # Escape HTML special characters in text.











                    text = (











                        run.text.replace("&", "&amp;")











                        .replace("<", "&lt;")











                        .replace(">", "&gt;")











                    )











                    if run.bold:











                        text = f"<strong>{text}</strong>"











                    if run.italic:











                        text = f"<em>{text}</em>"











                    parts.append(text)























            inner = "".join(parts).strip()











            if not inner:











                return ""











            if tag == "li":











                return f"<ul><li>{inner}</li></ul>"











            return f"<{tag}>{inner}</{tag}>"























        def table_to_html(table):
            from docx.table import Table

            rows = []

            for row in table.rows:

                cells = []

                for cell in row.cells:

                    cell_html = []

                    # Walk cell children in document order so that

                    # interleaved paragraphs and nested tables are both

                    # captured. cell.paragraphs alone skips w:tbl children.

                    for child in cell._element.iterchildren():

                        if child.tag == qn("w:p"):

                            for para in cell.paragraphs:

                                if para._element is child:

                                    h = para_to_html(para)

                                    if h:

                                        cell_html.append(h)

                                    break

                        elif child.tag == qn("w:tbl"):

                            nested = Table(child, cell)

                            h = table_to_html(nested)

                            if h:

                                cell_html.append(h)

                    cells.append(

                        "<td>" + "".join(cell_html) + "</td>"

                    )

                rows.append("<tr>" + "".join(cells) + "</tr>")

            if not rows:

                return ""

            return "<table>" + "".join(rows) + "</table>"

        # Walk the body in document order, interleaving paragraphs and tables.

        body = doc.element.body

        html_parts = []

        for child in body.iterchildren():

            if child.tag == qn("w:p"):

                # Find the matching Paragraph object.

                for para in doc.paragraphs:

                    if para._element is child:

                        h = para_to_html(para)

                        if h:

                            html_parts.append(h)

                        break

            elif child.tag == qn("w:tbl"):

                for table in doc.tables:

                    if table._element is child:

                        h = table_to_html(table)

                        if h:

                            html_parts.append(h)

                        break

        return "\n".join(html_parts) if html_parts else "[no content extracted from .docx]"

    except Exception as exc:

        return f"[failed to parse .docx: {exc}]"



def _extract_html_from_pdf(data: bytes) -> str:











    """Extract content from a .pdf file as HTML, preserving layout and images.























    Uses PyMuPDF (fitz) which provides ``get_text("html")`` for styled











    text and ``get_images()`` for embedded images. Falls back to pypdf











    plain-text extraction if PyMuPDF is unavailable.











    """











    import base64











    import io























    # Primary path: PyMuPDF.











    try:











        import fitz











    except ImportError:











        fitz = None























    if fitz is not None:











        try:











            pdf = fitz.open(stream=data, filetype="pdf")











            html_parts = []











            for page_num in range(len(pdf)):











                page = pdf[page_num]











                # Styled HTML for text on this page.











                page_html = page.get_text("html")











                if page_html and page_html.strip():











                    html_parts.append(page_html)























                # Extract embedded images as data URIs.











                for img_info in page.get_image_info(xrefs=True):











                    xref = img_info.get("xref")











                    if not xref:











                        continue











                    try:











                        img = pdf.extract_image(xref)











                        b64 = base64.b64encode(img["image"]).decode("ascii")











                        mime = f"image/{img.get('ext', 'png')}"











                        html_parts.append(











                            f'<img src="data:{mime};base64,{b64}" alt="PDF image on page {page_num + 1}" />'











                        )











                    except Exception:











                        pass











            pdf.close()











            if html_parts:







                return "\n".join(html_parts)







            return "[no content extracted from .pdf]"











        except Exception as exc:











            return f"[failed to parse .pdf with PyMuPDF: {exc}]"























    # Fallback: pypdf plain text (no images, no formatting).











    try:











        from pypdf import PdfReader











    except ImportError:











        try:











            from PyPDF2 import PdfReader











        except ImportError:











            return "[neither PyMuPDF nor pypdf installed; cannot parse .pdf]"























    try:











        reader = PdfReader(io.BytesIO(data))











        parts = []











        for page in reader.pages:











            text = page.extract_text() or ""











            if text.strip():











                # Escape and wrap in <pre> to preserve whitespace.











                escaped = (











                    text.replace("&", "&amp;")











                    .replace("<", "&lt;")











                    .replace(">", "&gt;")











                )











                parts.append(f"<pre>{escaped}</pre>")











        return "\n".join(parts) if parts else "[no text extracted from .pdf]"











    except Exception as exc:











        return f"[failed to parse .pdf with pypdf: {exc}]"



































def _extract_html_from_doc(data: bytes) -> str:



    """Extract content from a legacy .doc file as HTML via LibreOffice conversion.







    python-docx cannot read the binary .doc (OLE) format. Strategy:



    1. Try parsing as .docx directly (some .doc files are mislabeled .docx).



    2. Convert to .docx using LibreOffice headless, then reuse the docx



       extractor so tables, images, and formatting are preserved.



    3. If LibreOffice is unavailable or conversion fails, return a notice.



    """



    # Step 1: maybe it's actually a .docx (ZIP magic bytes PK).

    # _extract_html_from_docx catches its own exceptions and returns a

    # "[failed to parse ...]" string, so we check the return value rather

    # than relying on exceptions.

    if data[:4] == b"PK":

        result = _extract_html_from_docx(data)

        if not result.startswith("["):

            return result







    # Step 2: convert via LibreOffice



    import os



    import shutil



    import subprocess



    import tempfile







    soffice = shutil.which("soffice") or shutil.which("libreoffice")



    if not soffice:



        # Check common Windows install paths



        for candidate in (



            r"C:\Program Files\LibreOffice\program\soffice.exe",



            r"C:\Program Files (x86)\LibreOffice\program\soffice.exe",



        ):



            if os.path.isfile(candidate):



                soffice = candidate



                break



    if not soffice:



        return "[legacy .doc format requires LibreOffice for conversion; please install LibreOffice or convert to .docx]"







    tmpdir = tempfile.mkdtemp(prefix="agentao_doc_")



    src = os.path.join(tmpdir, "input.doc")



    try:



        with open(src, "wb") as f:



            f.write(data)



        # LibreOffice requires a user profile dir to avoid conflicts with



        # any running instance; -env:UserInstallation pins it.



        result = subprocess.run(



            [



                soffice,



                "--headless",



                "--norestore",



                "-env:UserInstallation=file://" + tmpdir.replace("\\", "/") + "/profile",



                "--convert-to", "docx",



                "--outdir", tmpdir,



                src,



            ],



            capture_output=True,



            timeout=120,



        )



        converted = os.path.join(tmpdir, "input.docx")



        if not os.path.isfile(converted):



            return "[LibreOffice conversion of .doc failed; please convert to .docx manually]"



        with open(converted, "rb") as f:



            docx_data = f.read()



        return _extract_html_from_docx(docx_data)



    except subprocess.TimeoutExpired:



        return "[LibreOffice conversion of .doc timed out; please convert to .docx manually]"



    except Exception as exc:



        return f"[LibreOffice conversion of .doc failed: {exc}; please convert to .docx manually]"



    finally:



        shutil.rmtree(tmpdir, ignore_errors=True)









def _save_base64_images(text: str, work_dir, attachment_name: str = "") -> str:

    """Save inline base64 data-URI images to workspace files and replace

    them with placeholders containing the saved file paths.



    Embedded images extracted from .docx/.pdf are inlined as

    ``<img src="data:image/png;base64,....">``.  In the text channel these

    are useless noise that massively inflates the token count (a 1 MB image

    becomes ~1.3 MB of base64 ~ 330 K tokens).  Instead of discarding them,

    each image is decoded and saved as a file under

    ``<work_dir>/attachments_images/``; the ``<img>`` tag is replaced with

    a placeholder referencing the file path so the model can call/read it

    later.

    """

    import base64

    import re

    from pathlib import Path



    if not work_dir:

        pattern = re.compile(

            r'<img[^>]*\bsrc="data:[^;]+;base64,[A-Za-z0-9+/=]*"[^>]*/?>',

            re.IGNORECASE,

        )

        return pattern.sub("[image omitted]", text)



    img_dir = Path(work_dir).expanduser().resolve() / "attachments_images"

    img_dir.mkdir(parents=True, exist_ok=True)



    prefix = re.sub(r'[^A-Za-z0-9._-]', '_', Path(attachment_name).stem)[:40] if attachment_name else "img"



    pattern = re.compile(

        r'<img[^>]*\bsrc="data:([^;]+);base64,([A-Za-z0-9+/=]*)"[^>]*/?>',

        re.IGNORECASE,

    )



    counter = [0]



    # Formats that require conversion to PNG for broad compatibility.
    # EMF/WMF are Windows vector metafiles unsupported by most viewers and
    # all LLM vision APIs. Pillow can render them via GDI on Windows.
    _CONVERT_TO_PNG = {"image/x-emf", "image/emf", "image/x-wmf", "image/wmf"}

    def _replacer(m):
        mime = m.group(1)
        b64_data = m.group(2)
        ext_map = {
            "image/png": ".png",
            "image/jpeg": ".jpg",
            "image/jpg": ".jpg",
            "image/gif": ".gif",
            "image/bmp": ".bmp",
            "image/webp": ".webp",
            "image/tiff": ".tiff",
            "image/svg+xml": ".svg",
        }
        counter[0] += 1
        try:
            raw = base64.b64decode(b64_data)
        except Exception:
            return f"[image: decode failed, mime={mime}]"

        needs_convert = mime.lower() in _CONVERT_TO_PNG

        # Also detect EMF/WMF by magic bytes when MIME is inaccurate.
        if not needs_convert and len(raw) >= 4:
            first4 = raw[:4]
            # EMF: EMR_HEADER record type=1, signature " EMF" at offset 40
            if first4 == b'\x01\x00\x00\x00' and len(raw) >= 44 and raw[40:44] == b' EMF':
                needs_convert = True
            # WMF placeable header starts with 0xD7CDC69A
            elif raw[:4] == b'\xd7\xcd\xc6\x9a':
                needs_convert = True

        if needs_convert:
            try:
                from PIL import Image
                import io as _io
                img = Image.open(_io.BytesIO(raw))
                if img.mode not in ("RGB", "RGBA"):
                    img = img.convert("RGB")
                filename = f"{prefix}_{counter[0]:03d}.png"
                filepath = img_dir / filename
                png_buf = _io.BytesIO()
                img.save(png_buf, format="PNG")
                filepath.write_bytes(png_buf.getvalue())
                return f"[image saved: {filepath}]"
            except Exception as exc:
                ext = ".emf" if "emf" in mime.lower() else (".wmf" if "wmf" in mime.lower() else ".png")
                filename = f"{prefix}_{counter[0]:03d}{ext}"
                filepath = img_dir / filename
                filepath.write_bytes(raw)
                return f"[image saved (conversion failed: {exc}): {filepath}]"

        ext = ext_map.get(mime.lower(), ".png")
        filename = f"{prefix}_{counter[0]:03d}{ext}"
        filepath = img_dir / filename
        filepath.write_bytes(raw)
        return f"[image saved: {filepath}]"

