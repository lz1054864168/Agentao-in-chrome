def _truncate_attachment_text(text: str, limit: int = 200_000) -> str:

    """Truncate a single attachment's text to ``limit`` characters.



    200 K chars ≈ 50 K tokens — generous for any reasonable document while

    preventing a single pathological attachment from consuming the entire

    context window.

    """

    if len(text) <= limit:

        return text

    half = limit // 2

    head = text[:half]

    tail = text[-half:]

    omitted = len(text) - limit

    return (

        head

        + f"\n\n[... {omitted} characters truncated ...]\n\n"

        + tail

    )





def _truncate_total(block: str, limit: int = 600_000) -> str:

    """Truncate the combined attachment block to ``limit`` characters.



    600 K chars ≈ 150 K tokens, leaving ample room for the system prompt,

    conversation history, and the model's response within a 256 K-token

    context window.

    """

    if len(block) <= limit:

        return block

    # Keep the beginning — it usually contains the first (most relevant)

    # attachment and its structure.

    return (

        block[:limit]

        + "\n\n[... remaining attachments truncated to fit context window ...]"

    )





